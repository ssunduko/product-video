// Trace -> DSL. Turns an observed walk of the app into a .demo script and its
// selector sidecar.
//
//   node author.mjs ../scenarios/<name>.trace.json [-o ../scripts/<name>.demo]
//
// Traces live in scenarios/; the .flow they came from lives in input/. Both are
// authored, both belong in review. The .demo and its selector sidecar are generated into
// scripts/ and can be deleted and rebuilt from the trace at any time.
//
// WHERE A TRACE COMES FROM
//
// You describe the flow in plain English. Claude drives the real app through
// the Chrome extension, actually performing it, and writes down what it did:
// which element each step touched, the selector that element answers to, and —
// the part that matters — HOW LONG each wait really took. That file is the
// trace. This turns it into the DSL the pipeline executes.
//
// WHY THE TIMINGS ARE THE POINT
//
// Everything else here is transcription; the timings are the reason this is
// code rather than a prompt. A `.demo` written by hand has to guess how long
// the app will take, and a guess that is wrong in the slow direction is not a
// small error: narration stops, the screen keeps moving, and the video goes
// silent for the difference. tighten.mjs cannot recover it either, because a
// streaming answer is not a frozen screen — dead air it can remove has to be
// frozen AND silent.
//
// That is not hypothetical. Both scripts in this repo were written with
// `hold 7s` against generation that measured 36.6s in one run and 43s in the
// next, and both produced double-digit silences that had to be found and fixed
// afterwards. So the generator sizes the narration budget from the observed
// wait, and when narration cannot reasonably cover it, says so and emits the
// SPEEDS_MS range to fast-forward the remainder at assemble time.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));

// Speech rate for budgeting. 15.5 came from dividing text length by the gap
// between cues, which silently included the pause AFTER each line — so it ran
// fast and the budgeter under-estimated every clip. Back-solved from three real
// overlap warnings on the mcp take, the true rate is 12.0-13.7 chars/sec.
//
// Deliberately set at the slow end: over-estimating a line only places one
// fewer line in a wait, while under-estimating makes two lines talk over each
// other, which narrate.mjs can warn about but not fix.
export const CHARS_PER_SEC = 12.5;
export const speechMs = (text) => Math.round((String(text).length / CHARS_PER_SEC) * 1000);

// A line needs a beat of air after it before the next one starts, or narrate.mjs
// warns that they overlap.
const LINE_GAP_MS = 900;

// Past this, stop adding narration and fast-forward the picture instead. Wall
// to wall talking over a 40s wait reads worse than a visible fast-forward, and
// it overlaps itself on a day the app answers quickly.
const NARRATION_CEILING_MS = 22000;

const q = (s) => `"${String(s).replace(/"/g, "'")}"`;

function fail(msg) {
  console.error(`author: ${msg}`);
  process.exit(1);
}

// ---- narration budgeting ----
// Given a wait that was observed to take `waitMs` and a pool of lines the
// author wants said over it, work out how many actually fit and what to do
// with whatever is left.
export function budget(waitMs, lines) {
  const placed = [];
  let cursor = 0;

  for (const line of lines) {
    const dur = speechMs(line);
    if (cursor + dur > Math.min(waitMs, NARRATION_CEILING_MS)) break;
    placed.push({ text: line, atMs: cursor, durMs: dur });
    cursor += dur + LINE_GAP_MS;
  }

  const coveredMs = placed.length ? placed.at(-1).atMs + placed.at(-1).durMs : 0;
  const uncoveredMs = Math.max(0, waitMs - coveredMs);

  return {
    placed,
    coveredMs,
    uncoveredMs,
    unused: lines.slice(placed.length),
    // Only worth a seam if it saves something noticeable.
    speedRange: uncoveredMs > 6000 ? [coveredMs + 1500, waitMs - 1500] : null,
  };
}

// ---- emit ----
export function demoFromTrace(trace) {
  if (!trace || !Array.isArray(trace.beats)) fail('trace needs a `beats` array');

  const notes = [];
  const selectors = new Map(); // name -> intent
  const resolutions = {}; // intent -> {spec, evidence}
  const speedRanges = [];
  let clock = 0; // ms into the take, for SPEEDS_MS ranges

  const out = [];
  const head = [];

  head.push(`# ${trace.description ?? trace.name ?? 'Generated demo'}`);
  head.push('#');
  head.push('# Generated by pipeline/author.mjs from an observed walk of the app.');
  head.push('# Holds and narration are sized from what the app ACTUALLY did, not');
  head.push('# from a guess — see the measured comments against each wait.');
  if (trace.observedAt) head.push(`# Observed: ${trace.observedAt}`);
  head.push('#');
  head.push('# Edit freely. Re-running the author overwrites it, so if you change');
  head.push('# a line here, change it in the trace too.');

  // Hazards the walk found that the DSL cannot express yet. Better in the file
  // than in a chat log nobody re-reads.
  for (const w of trace.warnings ?? []) {
    head.push('#');
    for (const line of String(w).split('\n')) head.push(`# ${line}`);
  }

  const body = [];


  // ---- beats ----
  const beatLines = [];

  for (const beat of trace.beats) {
    beatLines.push('');
    beatLines.push(`beat ${beat.title}`);

    const ref = (s) => {
      if (!s.intent) return null;
      const name = s.name ?? `sel${selectors.size + 1}`;
      if (!selectors.has(name)) selectors.set(name, s.intent);
      if (s.spec) resolutions[s.intent] = { spec: s.spec, evidence: s.evidence ?? 'observed live' };
      return `@${name}`;
    };

    const emitOne = (step) => {
      switch (step.op) {
        case 'say':
          beatLines.push(`  say ${q(step.text)}`);
          clock += speechMs(step.text);
          break;

        case 'hold':
          beatLines.push(`  hold ${(step.ms / 1000).toFixed(step.ms % 1000 ? 1 : 0)}s`);
          clock += step.ms;
          break;

        case 'wait':
          beatLines.push(
            `  wait ${ref(step)} within ${Math.max(10, Math.ceil((step.observedMs ?? 5000) * 3 / 1000))}s`,
          );
          clock += step.observedMs ?? 0;
          break;

        case 'type':
          beatLines.push(`  type ${q(step.text)} into ${ref(step)}`);
          clock += Math.max(1000, String(step.text).length * 30);
          break;

        case 'press':
          beatLines.push(`  press ${step.key}`);
          break;

        case 'click':
        case 'hover':
          beatLines.push(`  ${step.op} ${ref(step)}`);
          clock += 800;
          break;

        // The interesting one: a wait whose real duration we measured.
        case 'waitGone': {
          const waitMs = step.observedMs ?? 0;
          const b = budget(waitMs, step.narration ?? []);
          const waitStart = clock;

          // `say` does not block, so the hold after one line is what decides
          // when the next fires: hold = next line's start minus this one's.
          b.placed.forEach((line, i) => {
            beatLines.push(`  say ${q(line.text)}`);
            const next = b.placed[i + 1];
            if (next) beatLines.push(`  hold ${Math.round((next.atMs - line.atMs) / 1000)}s`);
          });

          // Say which it is. A number a reader trusts as measured, when it was
          // guessed, is worse than no number — it is the guess that produced
          // the silences this whole stage exists to prevent.
          beatLines.push(
            step.measured === false
              ? `  # ESTIMATED ${(waitMs / 1000).toFixed(1)}s here (not measured); ` +
                `${(b.coveredMs / 1000).toFixed(1)}s of it is narrated`
              : `  # measured ${(waitMs / 1000).toFixed(1)}s here; ` +
                `${(b.coveredMs / 1000).toFixed(1)}s of it is narrated`,
          );
          beatLines.push(
            `  wait ${ref(step)} gone within ${Math.max(60, Math.ceil((waitMs * 3) / 1000))}s`,
          );

          if (b.speedRange) {
            const [a, z] = b.speedRange;
            speedRanges.push([Math.round(waitStart + a), Math.round(waitStart + z)]);
            beatLines.push(
              `  # ${(b.uncoveredMs / 1000).toFixed(1)}s of this wait has no narration over it.`,
            );
            beatLines.push('  # Fast-forward it at assemble time (see the SPEEDS_MS note in the header).');
            notes.push(
              `${beat.title}: ${(waitMs / 1000).toFixed(1)}s wait, ` +
                `${(b.uncoveredMs / 1000).toFixed(1)}s uncovered -> SPEEDS_MS candidate`,
            );
          }

          for (const line of b.unused) {
            notes.push(`unused line (did not fit the ${(waitMs / 1000).toFixed(1)}s wait): "${line}"`);
          }

          clock += waitMs;

          if (step.result) {
            beatLines.push(`  say ${q(step.result)}`);
            clock += speechMs(step.result);
          }
          break;
        }

        // A guard for UI that only shows up sometimes — a consent bar, a
        // notification banner. Keep the timeout short: `appears` waits the
        // full window when the thing is absent, and absent is the normal case,
        // so a long one adds that pause to every guarded step of the take.
        case 'ifAppears': {
          const secs = step.timeoutS ?? 2;
          beatLines.push(`  if ${ref(step)} appears within ${secs}s`);
          const from = beatLines.length;
          for (const child of step.then ?? []) emitOne(child);
          for (let k = from; k < beatLines.length; k++) beatLines[k] = `  ${beatLines[k]}`;
          beatLines.push('  end');
          // Costs the guard window on every pass where the thing is absent.
          clock += secs * 1000;
          break;
        }

        default:
          fail(`unknown step op "${step.op}" in beat "${beat.title}"`);
      }
    };

    for (const step of beat.steps ?? []) emitOne(step);
  }

  // ---- header ----
  if (speedRanges.length) {
    head.push('#');
    head.push('# GENERATION IS SLOWER THAN NARRATION CAN COVER. After recording, fast-');
    head.push('# forward these spans rather than cutting them — the answer appearing on');
    head.push('# screen is the payoff, so a cut lands the viewer on a finished table');
    head.push('# they never saw arrive. tighten.mjs cannot do it (not a frozen screen):');
    head.push('#');
    head.push(
      `#   $env:SPEEDS_MS='${JSON.stringify(speedRanges.map(([a, z]) => [a, z, 4]))}'; ` +
        `$env:OUT_NAME='cut.mp4'; node assemble.mjs`,
    );
    head.push('#');
    head.push('# Those offsets are predicted from the observed walk. Check them against');
    head.push("# assemble.mjs's gap report on the real take before committing to them.");
  }

  out.push(head.join('\n'));
  out.push('');
  if (trace.name) out.push(`name: ${trace.name}`);
  if (trace.description) out.push(`description: ${trace.description}`);
  if (trace.target) out.push(`target: ${trace.target}`);
  if (trace.app && !trace.target) out.push(`app: ${trace.app}`);
  if (trace.viewport) out.push(`viewport: ${trace.viewport}`);
  if (trace.intro) out.push(`intro: ${trace.intro}`);
  if (trace.outro) out.push(`outro: ${trace.outro}`);

  out.push('');
  out.push('# Stated as intent; resolved against the live DOM into the sidecar beside');
  out.push('# this file. Re-resolve after a redesign — this script does not change.');
  out.push('selectors:');
  const width = Math.max(...[...selectors.keys()].map((k) => k.length), 4);
  for (const [name, intent] of selectors) {
    out.push(`  ${name.padEnd(width)} = ask ${q(intent)}`);
  }

  out.push(...beatLines);

  // Every script must end on a hold or the final zoom has nowhere to settle.
  const lastReal = [...beatLines].reverse().find((l) => l.trim() && !l.trim().startsWith('#'));
  if (!lastReal || !/^\s*hold /.test(lastReal)) {
    out.push('');
    out.push('# The take needs a beat at the end for the last line to finish and the');
    out.push('# final zoom to settle.');
    out.push('beat Settle');
    out.push('  hold 4s');
  }

  // Provenance has to come from the trace, not be stamped on unconditionally.
  // A sidecar that claims "observed live" over a hand-authored trace is the one
  // lie that makes every other entry untrustworthy.
  const sidecar = {
    resolvedAgainst: trace.app ?? trace.target ?? 'unknown',
    resolvedAt: trace.observedAt ?? 'unrecorded — set observedAt in the trace',
    resolvedBy: trace.resolvedBy ?? 'hand-authored trace (not resolved live)',
    note:
      trace.provenance ??
      'Generated with the .demo by pipeline/author.mjs from one trace, so the two agree by construction. ' +
        'Whether the specs were observed live depends on how that trace was produced — see resolvedBy.',
    selectors: resolutions,
  };

  return { demo: `${out.join('\n')}\n`, sidecar, notes, speedRanges };
}

// ---- CLI ----
const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  const argv = process.argv.slice(2);
  let input = null;
  let output = null;
  let print = false;

  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-o' || a === '--out') output = argv[++i];
    else if (a === '--print') print = true;
    else if (!input) input = a;
    else fail(`unexpected argument "${a}"`);
  }

  if (!input) {
    fail('usage: node author.mjs ../scenarios/<name>.trace.json [-o ../scripts/<name>.demo] [--print]');
  }

  const trace = JSON.parse(fs.readFileSync(path.resolve(input), 'utf8').replace(/^﻿/, ''));
  const { demo, sidecar, notes } = demoFromTrace(trace);

  if (print) {
    console.log(demo);
  } else {
    const base = trace.name ?? path.basename(input).replace(/\.[^.]+$/, '');
    const demoPath = path.resolve(output ?? path.join(HERE, '..', 'scripts', `${base}.demo`));
    const sidePath = demoPath.replace(/\.[^.\\/]+$/, '') + '.selectors.json';

    fs.mkdirSync(path.dirname(demoPath), { recursive: true });
    fs.writeFileSync(demoPath, demo);
    fs.writeFileSync(sidePath, `${JSON.stringify(sidecar, null, 2)}\n`);

    console.log(demoPath);
    console.log(sidePath);
  }

  for (const n of notes) console.error(`  note: ${n}`);
}
